def test_concrete_issue_port_uses_numeric_endpoints_and_exact_fields() -> None:
    calls: list[tuple[str, ...]] = []
    responses: list[object] = [
        [],
        {"iid": 71},
        {"iid": 71},
        {
            "project_id": 310967,
            "iid": 71,
            "title": "title",
            "description": "body",
            "labels": ["x"],
            "state": "opened",
        },
    ]

    def run(command: tuple[str, ...], **_kwargs: object) -> CommandResult:
        calls.append(command)
        return CommandResult(0, json.dumps(responses.pop(0)), "")

    port = gitlab.GitLabIssuePublisher(
        host="gitlab.example", project_id=310967, glab_path="/bin/glab", run_command=run
    )
    assert port.list_issues(project_id=310967, marker="marker") == ()
    port.create_issue(
        project_id=310967, title="title", description="body", labels=("x",)
    )
    port.update_issue(
        project_id=310967, iid=71, title="title", description="body", labels=("x",)
    )
    assert port.fetch_issue(project_id=310967, iid=71)["iid"] == 71
    assert "projects/310967/issues" in calls[0] and "page=1" in calls[0]
    assert calls[0][calls[0].index("-X") + 1] == "GET"
    assert calls[1][calls[1].index("-X") + 1] == "POST"
    assert [
        part
        for part in calls[1]
        if part.startswith(("title=", "description=", "labels="))
    ] == ["title=title", "description=body", "labels=x"]
    assert calls[2][calls[2].index("-X") + 1] == "PUT"
    assert [
        part
        for part in calls[2]
        if part.startswith(("title=", "description=", "labels="))
    ] == ["title=title", "description=body", "labels=x"]
    assert calls[3][calls[3].index("-X") + 2] == "projects/310967/issues/71"


