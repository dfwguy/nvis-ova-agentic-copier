def test_issue_publish_cli_exposes_json_help_dry_run_and_apply_contract() -> None:
    calls: list[dict[str, object]] = []

    def publish_issue(**kwargs: object) -> Any:
        calls.append(dict(kwargs))
        return type(
            "Report",
            (),
            {
                "applied": kwargs["apply"],
                "action": "create" if kwargs["apply"] else "would-create",
                "description": "## Problem\nBody",
                "marker": "<!-- marker -->",
                "issue": (
                    type("Issue", (), {"iid": 71, "web_url": "https://gitlab/71"})()
                    if kwargs["apply"]
                    else None
                ),
            },
        )()

    common = [
        "issue",
        "publish",
        "--title",
        "Publish Markdown",
        "--problem",
        "Body",
        "--outcome",
        "Publish correctly",
        "--acceptance",
        "`uv run pytest` passes",
        "--acceptance",
        "Read-back matches",
        "--marker",
        ISSUE_MARKER,
        "--label",
        "agent::factory",
        "--priority",
        "high",
        "--severity",
        "medium",
    ]
    output: list[str] = []

    assert (
        main(
            [*common, "--json"], publish_issue=publish_issue, write_stdout=output.append
        )
        == 0
    )
    assert calls == [
        {
            "title": "Publish Markdown",
            "problem": "Body",
            "outcome": "Publish correctly",
            "acceptance": ("`uv run pytest` passes", "Read-back matches"),
            "impact": None,
            "additional_context": None,
            "marker": ISSUE_MARKER,
            "priority": "high",
            "severity": "medium",
            "labels": ("agent::factory",),
            "issue_iid": None,
            "apply": False,
        }
    ]
    assert '"applied": false' in output.pop()
    assert (
        main(
            [*common, "--apply"],
            publish_issue=publish_issue,
            write_stdout=output.append,
        )
        == 0
    )
    assert calls[-1]["apply"] is True

    with pytest.raises(SystemExit) as help_exit:
        main(["issue", "publish", "--help"])
    assert help_exit.value.code == 0
    with pytest.raises(SystemExit) as invalid_exit:
        main(["issue", "publish", "--title", "missing-required-fields"])
    assert invalid_exit.value.code == 2


