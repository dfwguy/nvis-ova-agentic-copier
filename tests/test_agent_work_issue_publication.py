class RecordingIssuePort:
    """Record the explicit issue-publication transport calls."""

    def __init__(
        self,
        *,
        existing_iid: int | None = None,
        existing_description: object = "<!-- agent-work-issue-publication:v1 -->",
    ) -> None:
        self.existing_iid = existing_iid
        self.existing_description = existing_description
        self.calls: list[tuple[str, dict[str, object]]] = []

    def list_issues(
        self, *, project_id: int, marker: str
    ) -> tuple[dict[str, object], ...]:
        self.calls.append(("list", {"project_id": project_id, "marker": marker}))
        if self.existing_iid is None:
            return ()
        return (
            {
                "project_id": project_id,
                "iid": self.existing_iid,
                "title": "Existing title",
                "description": self.existing_description,
                "labels": ("old",),
                "state": "opened",
            },
        )

    def create_issue(self, **kwargs: object) -> dict[str, object]:
        self.calls.append(("create", dict(kwargs)))
        return {"iid": 71, **kwargs}

    def update_issue(self, **kwargs: object) -> dict[str, object]:
        self.calls.append(("update", dict(kwargs)))
        return dict(kwargs)

    def fetch_issue(self, *, project_id: int, iid: int) -> dict[str, object]:
        self.calls.append(("fetch", {"project_id": project_id, "iid": iid}))
        mutation = next(
            values
            for action, values in reversed(self.calls)
            if action in {"create", "update"}
        )
        return {"iid": iid, **mutation}


def _publish(
    port: RecordingIssuePort,
    *,
    apply: bool,
    issue_iid: int | None = None,
    problem: str = "Publishing issue bodies as escaped text hides the review intent.",
) -> gitlab.IssuePublicationReport:
    """Exercise the public boundary with scalar, reviewable content."""
    return gitlab.publish_issue(
        project_id=310967,
        title="Publish structured issue Markdown",
        problem=problem,
        impact="Reviewers cannot reliably assess the requested work.",
        outcome="Publish one canonical Markdown issue body.",
        acceptance=("`uv run pytest` passes", "The read-back is exact"),
        additional_context="Generated by the factory issue publisher.",
        marker="<!-- agent-work-issue-publication:v1 -->",
        priority="high",
        severity="medium",
        labels=("agent::factory", "kind::enhancement"),
        issue_iid=issue_iid,
        apply=apply,
        port=port,
    )


def test_issue_publication_preview_renders_canonical_markdown_without_mutation() -> (
    None
):
    port = RecordingIssuePort()

    report = _publish(port, apply=False)

    assert report.applied is False
    assert report.action == "would-create"
    assert report.issue is None
    assert report.description == (
        "## Problem\n"
        "Publishing issue bodies as escaped text hides the review intent.\n\n"
        "## Impact\n"
        "Reviewers cannot reliably assess the requested work.\n\n"
        "## Outcome\n"
        "Publish one canonical Markdown issue body.\n\n"
        "## Acceptance criteria\n"
        "- `uv run pytest` passes\n"
        "- The read-back is exact\n\n"
        "## Additional context\n"
        "Generated by the factory issue publisher.\n\n"
        "## Priority\n"
        "high\n\n"
        "## Severity\n"
        "medium\n\n"
        "<!-- agent-work-issue-publication:v1 -->"
    )
    assert port.calls == []


@pytest.mark.parametrize(
    "unsafe_value",
    (
        pytest.param("literal\\nnewline", id="literal-backslash-n"),
        pytest.param("literal\\r\\nnewline", id="literal-backslash-r-n"),
        pytest.param("percent%0Anewline", id="percent-encoded-lf"),
        pytest.param("percent%0Dnewline", id="percent-encoded-cr"),
    ),
)
def test_issue_publication_rejects_escaped_line_break_text_before_port_calls(
    unsafe_value: str,
) -> None:
    port = RecordingIssuePort()

    with pytest.raises(gitlab.IssuePublicationError, match="linebreak"):
        _publish(port, apply=False, problem=unsafe_value)

    assert port.calls == []


@pytest.mark.parametrize(
    ("existing_iid", "issue_iid", "expected_action"),
    (
        pytest.param(None, None, "create", id="create"),
        pytest.param(71, 71, "update", id="update"),
    ),
)
def test_issue_publication_apply_mutates_once_then_reads_back_every_requested_field(
    existing_iid: int | None, issue_iid: int | None, expected_action: str
) -> None:
    port = RecordingIssuePort(existing_iid=existing_iid)
    canonical_description = _publish(RecordingIssuePort(), apply=False).description

    report = _publish(port, apply=True, issue_iid=issue_iid)

    assert report.applied is True
    assert report.action == expected_action
    assert report.issue is not None
    assert report.issue.project_id == 310967
    assert report.issue.iid == 71
    assert report.issue.title == "Publish structured issue Markdown"
    assert report.issue.description == report.description
    assert report.description == canonical_description
    assert report.issue.labels == ("agent::factory", "kind::enhancement")
    assert report.issue.state == "opened"
    mutations = [call for call in port.calls if call[0] in {"create", "update"}]
    assert len(mutations) == 1
    assert port.calls[-1] == ("fetch", {"project_id": 310967, "iid": 71})


