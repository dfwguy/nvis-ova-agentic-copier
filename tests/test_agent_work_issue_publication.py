ISSUE_MARKER = "<!-- agent-work-issue-publication:structured-markdown -->"


class RecordingIssuePort:
    """Record the explicit issue-publication transport calls."""

    def __init__(
        self,
        *,
        existing_iid: int | None = None,
        existing_description: object = ISSUE_MARKER,
    ) -> None:
        self.existing_iid = existing_iid
        self.existing_description = existing_description
        self.calls: list[tuple[str, dict[str, object]]] = []

    def list_issues(
        self, *, project_id: int, marker: str
    ) -> tuple[dict[str, object], ...]:
        self.calls.append(("list", {"project_id": project_id, "marker": marker}))
        if self.existing_iid is None:
            return ()
        return (
            {
                "project_id": project_id,
                "iid": self.existing_iid,
                "title": "Existing title",
                "description": self.existing_description,
                "labels": ("old",),
                "state": "opened",
            },
        )

    def create_issue(self, **kwargs: object) -> dict[str, object]:
        self.calls.append(("create", dict(kwargs)))
        return {"iid": 71, **kwargs}

    def update_issue(self, **kwargs: object) -> dict[str, object]:
        self.calls.append(("update", dict(kwargs)))
        return dict(kwargs)

    def fetch_issue(self, *, project_id: int, iid: int) -> dict[str, object]:
        self.calls.append(("fetch", {"project_id": project_id, "iid": iid}))
        mutation = next(
            values
            for action, values in reversed(self.calls)
            if action in {"create", "update"}
        )
        return {"iid": iid, **mutation}


def _publish(
    port: RecordingIssuePort,
    *,
    apply: bool,
    issue_iid: int | None = None,
    problem: str = "Publishing issue bodies as escaped text hides the review intent.",
    feedback_audit: bool = False,
    audit_feedback: Callable[[], None] | None = None,
) -> gitlab.IssuePublicationReport:
    """Exercise the public boundary with scalar, reviewable content."""
    return gitlab.publish_issue(
        project_id=310967,
        title="Publish structured issue Markdown",
        problem=problem,
        impact="Reviewers cannot reliably assess the requested work.",
        outcome="Publish one canonical Markdown issue body.",
        acceptance=("`uv run pytest` passes", "The read-back is exact"),
        additional_context="Generated by the factory issue publisher.",
        marker=ISSUE_MARKER,
        priority="high",
        severity="medium",
        labels=("agent::factory", "kind::enhancement"),
        issue_iid=issue_iid,
        apply=apply,
        port=port,
        feedback_audit=feedback_audit,
        audit_feedback=audit_feedback,
    )


